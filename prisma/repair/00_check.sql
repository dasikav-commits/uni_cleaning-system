SELECT e.kind AS missing, e.parent, e.name
FROM expected e
WHERE (e.kind = 'table' AND NOT EXISTS (
         SELECT 1 FROM information_schema.tables t WHERE t.table_schema = 'public' AND t.table_name = e.parent))
   OR (e.kind = 'column' AND NOT EXISTS (
         SELECT 1 FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = e.parent AND c.column_name = e.name))
   OR (e.kind = 'enum value' AND NOT EXISTS (
         SELECT 1 FROM pg_enum v JOIN pg_type t ON t.oid = v.enumtypid JOIN pg_namespace n ON n.oid = t.typnamespace
         WHERE n.nspname = 'public' AND t.typname = e.parent AND v.enumlabel = e.name))
ORDER BY CASE e.kind WHEN 'table' THEN 1 WHEN 'column' THEN 2 ELSE 3 END, e.parent, e.name;
